import { beforeAll, afterAll, describe, it, expect } from "vitest";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
let db: PGlite;
const uid = "00000000-0000-4000-8000-000000000001";
const other = "00000000-0000-4000-8000-000000000002";
beforeAll(async () => {
  db = new PGlite();
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
    CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY);
    CREATE TABLE public.posts(id text PRIMARY KEY);
    CREATE TABLE public.reactions(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, target_type text NOT NULL, target_id text NOT NULL,
      user_id uuid NOT NULL REFERENCES auth.users(id), reaction_type text NOT NULL,
      UNIQUE(target_type,target_id,user_id,reaction_type));
    INSERT INTO auth.users VALUES ('${uid}'), ('${other}');
    INSERT INTO public.posts VALUES ('post-1');
    INSERT INTO public.reactions(target_type,target_id,user_id,reaction_type) VALUES ('post','post-1','${uid}','upvote');`);
  await db.exec(await readFile("supabase/migrations/0006_tsrg_foundation.sql", "utf8"));
  const sql = await readFile("supabase/migrations/0007_identity_reactions_flags.sql", "utf8");
  await db.exec(sql); await db.exec(sql);
}, 30000);
afterAll(async () => { await db.close(); });
describe("P0 isolated database scaffolding", () => {
  it("keeps legacy source explicit and prevents duplicate mapping", async () => {
    expect((await db.query("SELECT reaction_tier_source FROM public.reactions")).rows).toEqual([{ reaction_tier_source: "legacy_default" }]);
    await db.query("INSERT INTO public.user_identity_map(firebase_subject,supabase_uid) VALUES ($1,$2)", ["firebase-alice", uid]);
    await expect(db.query("INSERT INTO public.user_identity_map(firebase_subject,supabase_uid) VALUES ($1,$2)", ["firebase-other", uid])).rejects.toMatchObject({ code: "23505" });
    expect((await db.query("SELECT supabase_uid FROM public.user_identity_map WHERE firebase_subject=$1", ["firebase-alice"])).rows).toEqual([{ supabase_uid: uid }]);
  });
  it("rejects unmapped users and rolls back deletion if an insertion fails", async () => {
    await expect(db.query("SELECT public.toggle_post_reaction_atomic($1,$2,$3)", ["unknown", "post-1", "downvote"])).rejects.toMatchObject({ code: "42501" });
    await db.exec("ALTER TABLE public.reactions ADD CONSTRAINT simulate_failure CHECK (reaction_type <> 'downvote')");
    await expect(db.query("SELECT public.toggle_post_reaction_atomic($1,$2,$3)", ["firebase-alice", "post-1", "downvote"])).rejects.toMatchObject({ code: "23514" });
    expect((await db.query("SELECT reaction_type FROM public.reactions")).rows).toEqual([{ reaction_type: "upvote" }]);
    await db.exec("ALTER TABLE public.reactions DROP CONSTRAINT simulate_failure");
    const result = await db.query<{ result: unknown }>("SELECT public.toggle_post_reaction_atomic($1,$2,$3) AS result", ["firebase-alice", "post-1", "downvote"]);
    expect(result.rows[0].result).toMatchObject({ reactions: { upvote: 0, downvote: 1, repost: 0 } });
  });
  it("defaults every server flag off and denies untrusted table and RPC grants", async () => {
    const flags = await db.query<{ enabled: boolean }>("SELECT enabled FROM public.server_feature_flags");
    expect(flags.rows.length).toBeGreaterThan(0);
    expect(flags.rows.every(row => !row.enabled)).toBe(true);
    const privileges = await db.query("SELECT has_table_privilege('authenticated','public.user_identity_map','select') AS can_read, has_function_privilege('authenticated','public.toggle_post_reaction_atomic(text,text,text)','execute') AS can_execute");
    expect(privileges.rows[0]).toEqual({ can_read: false, can_execute: false });
  });
});
