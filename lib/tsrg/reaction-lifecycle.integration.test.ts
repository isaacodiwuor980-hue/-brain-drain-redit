import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

// Disposable in-memory database, synthetic accounts only. The API must still
// authenticate the subject: the service-role RPC cannot prove caller identity.
let db: PGlite;
const subjects = ["synthetic-a", "synthetic-b", "synthetic-c"];
const uids = subjects.map((_, i) => `00000000-0000-4000-8000-${String(i + 1).padStart(12, "0")}`);
const posts = ["fixture-0", "fixture-1", "fixture-2"];
const types = ["upvote", "downvote", "repost"] as const;
type Reaction = typeof types[number];

beforeAll(async () => {
  db = new PGlite();
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
    CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY);
    CREATE TABLE public.posts(id text PRIMARY KEY);
    CREATE TABLE public.reactions(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, target_type text NOT NULL, target_id text NOT NULL, user_id uuid NOT NULL REFERENCES auth.users(id), reaction_type text NOT NULL, UNIQUE(target_type,target_id,user_id,reaction_type));`);
  for (const file of ["0006_tsrg_foundation.sql", "0007_identity_reactions_flags.sql"]) await db.exec(await readFile(`supabase/migrations/${file}`, "utf8"));
  for (let i = 0; i < subjects.length; i++) {
    await db.query("INSERT INTO auth.users VALUES ($1)", [uids[i]]);
    await db.query("INSERT INTO public.user_identity_map(firebase_subject,supabase_uid) VALUES ($1,$2)", [subjects[i], uids[i]]);
  }
  for (const post of posts) await db.query("INSERT INTO public.posts VALUES ($1)", [post]);
}, 30000);
afterAll(async () => { await db?.close(); });

async function toggle(subject: string, post: string, type: Reaction) {
  return (await db.query<{ result: { reactions: Record<Reaction, number> } }>("SELECT public.toggle_post_reaction_atomic($1,$2,$3) AS result", [subject, post, type])).rows[0].result;
}

describe("synthetic reaction write/delete lifecycle", () => {
  it("matches an independent state model across 240 writes, switches and deletions", async () => {
    const state = new Map<string, Set<Reaction>>();
    let creations = 0, removals = 0, switches = 0;
    let seed = 42;
    const random = () => { seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0; return seed; };
    for (let step = 0; step < 240; step++) {
      const user = random() % subjects.length, post = posts[random() % posts.length], type = types[random() % types.length];
      const key = `${user}:${post}`;
      const current = state.get(key) ?? new Set<Reaction>();
      const wasPresent = current.has(type);
      if (wasPresent) removals++;
      else if (type !== "repost" && (current.has("upvote") || current.has("downvote"))) switches++;
      else creations++;
      if (type === "repost") current.delete("repost");
      else { current.delete("upvote"); current.delete("downvote"); }
      if (!wasPresent) current.add(type);
      state.set(key, current);
      const result = await toggle(subjects[user], post, type);
      const expected = { upvote: 0, downvote: 0, repost: 0 };
      for (let i = 0; i < subjects.length; i++) for (const reaction of state.get(`${i}:${post}`) ?? []) expected[reaction]++;
      expect(result.reactions).toEqual(expected);
      const rows = await db.query<{ user_id: string; reaction_type: Reaction }>("SELECT user_id,reaction_type FROM public.reactions WHERE target_type='post' AND target_id=$1", [post]);
      const expectedRows = subjects.flatMap((_, i) => [...(state.get(`${i}:${post}`) ?? [])].map(reaction => `${uids[i]}:${reaction}`)).sort();
      expect(rows.rows.map(row => `${row.user_id}:${row.reaction_type}`).sort()).toEqual(expectedRows);
    }
    expect(creations).toBeGreaterThan(0);
    expect(removals).toBeGreaterThan(0);
    expect(switches).toBeGreaterThan(0);
  }, 30000);
  it("rolls back a reaction write and its deletion when the transaction aborts", async () => {
    const before = (await db.query("SELECT target_id,user_id,reaction_type FROM public.reactions ORDER BY target_id,user_id,reaction_type")).rows;
    await db.exec("BEGIN");
    try {
      await toggle(subjects[0], posts[0], "upvote");
      await toggle(subjects[0], posts[0], "upvote");
    } finally {
      await db.exec("ROLLBACK");
    }
    expect((await db.query("SELECT target_id,user_id,reaction_type FROM public.reactions ORDER BY target_id,user_id,reaction_type")).rows).toEqual(before);
  });
  it("rejects unknown identities and missing posts without changing any existing reactions", async () => {
    const before = (await db.query("SELECT target_id,user_id,reaction_type FROM public.reactions ORDER BY target_id,user_id,reaction_type")).rows;
    await expect(toggle("unknown-synthetic", posts[0], "upvote")).rejects.toMatchObject({ code: "42501" });
    await expect(toggle(subjects[0], "missing-synthetic-post", "upvote")).rejects.toMatchObject({ code: "P0002" });
    expect((await db.query("SELECT target_id,user_id,reaction_type FROM public.reactions ORDER BY target_id,user_id,reaction_type")).rows).toEqual(before);
  });
  it("denies direct RPC access to untrusted roles", async () => {
    const result = await db.query("SELECT has_function_privilege('anon','public.toggle_post_reaction_atomic(text,text,text)','EXECUTE') AS anon, has_function_privilege('authenticated','public.toggle_post_reaction_atomic(text,text,text)','EXECUTE') AS authenticated");
    expect(result.rows).toEqual([{ anon: false, authenticated: false }]);
  });
});
