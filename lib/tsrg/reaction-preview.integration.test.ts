import { beforeAll, beforeEach, afterAll, describe, expect, it } from "vitest";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
let db: PGlite;
const uid = "00000000-0000-4000-8000-000000000001";
beforeAll(async () => {
  db = new PGlite();
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role; CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY);
    CREATE TABLE public.posts(id text PRIMARY KEY); CREATE TABLE public.reactions(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, target_type text NOT NULL, target_id text NOT NULL, user_id uuid NOT NULL, reaction_type text NOT NULL, UNIQUE(target_type,target_id,user_id,reaction_type));
    INSERT INTO auth.users VALUES ('${uid}'); INSERT INTO public.posts VALUES ('post-1');`);
  for (const file of ["0006_tsrg_foundation.sql", "0007_identity_reactions_flags.sql", "0008_set_post_reaction.sql", "0009_reaction_preview.sql"]) await db.exec(await readFile(`supabase/migrations/${file}`, "utf8"));
  await db.exec(await readFile("supabase/migrations/0009_reaction_preview.sql", "utf8"));
}, 30000);
beforeEach(async () => { await db.exec("DELETE FROM public.reactions"); });
afterAll(async () => { await db.close(); });
async function preview(type = "upvote") {
  const before = (await db.query("SELECT * FROM public.reactions ORDER BY id")).rows;
  const result = (await db.query<{ result: { action: string; concurrency_token: null } }>("SELECT public.preview_reaction_state($1,$2,$3) result", [uid, "post-1", type])).rows[0].result;
  expect((await db.query("SELECT * FROM public.reactions ORDER BY id")).rows).toEqual(before);
  expect(result.concurrency_token).toBeNull(); return result;
}
async function add(type: string) { await db.query("INSERT INTO public.reactions(target_type,target_id,user_id,reaction_type) VALUES('post','post-1',$1,$2)", [uid, type]); }
describe("read-only desired-state preview on simplified PGlite schema", () => {
  it("reports insert for absent vote", async () => expect((await preview()).action).toBe("insert"));
  it("reports noop for same vote", async () => { await add("upvote"); expect((await preview()).action).toBe("noop"); });
  it("reports direction flip for opposite vote", async () => { await add("downvote"); expect((await preview()).action).toBe("flip_direction"); });
  it("reports legacy dual-vote repair and keeps repost independent", async () => { await add("upvote"); await add("downvote"); expect((await preview()).action).toBe("remove_opposite"); expect((await preview("repost")).action).toBe("insert"); });
  it("rejects invalid direction and unknown posts", async () => {
    await expect(db.query("SELECT public.preview_reaction_state($1,$2,$3)", [uid, "post-1", "tier"])) .rejects.toMatchObject({ code: "22023" });
    await expect(db.query("SELECT public.preview_reaction_state($1,$2,$3)", [uid, "missing", "upvote"])).rejects.toMatchObject({ code: "P0002" });
  });
  it("denies anon/authenticated and grants only the service role", async () => {
    const privileges = await db.query("SELECT has_function_privilege('anon','public.preview_reaction_state(uuid,text,text)','execute') AS anon, has_function_privilege('authenticated','public.preview_reaction_state(uuid,text,text)','execute') AS authenticated, has_function_privilege('service_role','public.preview_reaction_state(uuid,text,text)','execute') AS service");
    expect(privileges.rows[0]).toEqual({ anon: false, authenticated: false, service: true });
  });
});
