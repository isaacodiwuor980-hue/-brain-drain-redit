import { beforeAll, beforeEach, afterAll, describe, expect, it } from "vitest";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
let db: PGlite;
const uid = "00000000-0000-4000-8000-000000000001";
beforeAll(async () => {
  db = new PGlite();
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
    CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY);
    CREATE TABLE public.posts(id text PRIMARY KEY);
    CREATE TABLE public.reactions(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, target_type text NOT NULL, target_id text NOT NULL, user_id uuid NOT NULL REFERENCES auth.users(id), reaction_type text NOT NULL, UNIQUE(target_type,target_id,user_id,reaction_type));
    INSERT INTO auth.users VALUES ('${uid}'); INSERT INTO public.posts VALUES ('post-1');`);
  for (const path of ["0006_tsrg_foundation.sql", "0007_identity_reactions_flags.sql", "0008_set_post_reaction.sql"]) await db.exec(await readFile(`supabase/migrations/${path}`, "utf8"));
  await db.exec(await readFile("supabase/migrations/0008_set_post_reaction.sql", "utf8"));
  await db.query("INSERT INTO public.user_identity_map(firebase_subject,supabase_uid) VALUES ($1,$2)", ["alice", uid]);
}, 30000);
beforeEach(async () => { await db.exec("DELETE FROM public.reactions"); });
afterAll(async () => { await db.close(); });
async function set(type: string) { return (await db.query<{ result: unknown }>("SELECT public.set_post_reaction_atomic($1,$2,$3) AS result", ["alice", "post-1", type])).rows[0].result; }
async function reactions() { return (await db.query<{ reaction_type: string }>("SELECT reaction_type FROM public.reactions ORDER BY reaction_type")).rows.map(x => x.reaction_type); }
describe("idempotent reaction desired-state setter", () => {
  it("inserts a missing reaction and reports the state", async () => {
    expect(await set("upvote")).toEqual({ postId: "post-1", reactionType: "upvote" });
    expect(await reactions()).toEqual(["upvote"]);
  });
  it("leaves the same reaction unchanged on repeated requests", async () => {
    await set("upvote"); const before = (await db.query("SELECT id FROM public.reactions")).rows;
    await set("upvote"); expect((await db.query("SELECT id FROM public.reactions")).rows).toEqual(before);
  });
  it("changes the opposite vote without disturbing a repost", async () => {
    await set("downvote"); const original = (await db.query("SELECT id FROM public.reactions WHERE reaction_type='downvote'")).rows; await set("repost");
    expect(await set("upvote")).toEqual({ postId: "post-1", reactionType: "upvote" });
    expect(await reactions()).toEqual(["repost", "upvote"]);
    expect((await db.query("SELECT id FROM public.reactions WHERE reaction_type='upvote'")).rows).toEqual(original);
  });
  it("rejects unmapped identities and denies untrusted execution", async () => {
    await expect(db.query("SELECT public.set_post_reaction_atomic($1,$2,$3)", ["unknown", "post-1", "upvote"])).rejects.toMatchObject({ code: "42501" });
    const grants = await db.query("SELECT has_function_privilege('authenticated','public.set_post_reaction_atomic(text,text,text)','execute') AS allowed");
    expect(grants.rows[0]).toEqual({ allowed: false });
  });
});
